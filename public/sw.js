// Minimaler Service Worker: App-Dateien für die Offline-Nutzung im Studio zwischenspeichern.
// Strategie: Netzwerk zuerst (aktuelle Version), bei fehlender Verbindung aus dem Cache.
const CACHE = "zweier-split-v1";

self.addEventListener("install", () => self.skipWaiting());
self.addEventListener("activate", (event) => event.waitUntil(self.clients.claim()));

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    fetch(req)
      .then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy));
        }
        return res;
      })
      .catch(() =>
        caches.match(req, { ignoreSearch: true }).then((hit) => hit || caches.match("/")),
      ),
  );
});
